def render_uiux_breakdown_html(sec_num):
    s = SECTIONS_SPECS.get(sec_num)
    if not s:
        return ""

    # Generate Color items
    colors_html = []
    for label, hex_code, swatch_bg, desc in s["colors"]:
        colors_html.append(f'''
          <div class="breakdown-item">
            <span class="breakdown-item-key"><span class="color-swatch-mini" style="background:{swatch_bg};"></span>{label}</span>
            <span class="breakdown-item-val" style="color:#ffd166;">{hex_code}</span>
          </div>''')
    colors_rendered = "\n".join(colors_html)

    # Generate Typography items
    typo_html = []
    for label, font_fam, spec, desc in s["typography"]:
        typo_html.append(f'''
          <div class="breakdown-item">
            <span class="breakdown-item-key">{label}</span>
            <span class="breakdown-item-val">{font_fam} <span style="color:#94a3b8; font-size:8.5px;">({spec})</span></span>
          </div>''')
    typo_rendered = "\n".join(typo_html)

    # Generate Component items
    comp_html = []
    for label, val, sub, desc in s["components"]:
        comp_html.append(f'''
          <div class="breakdown-item">
            <span class="breakdown-item-key">{label}</span>
            <span class="breakdown-item-val">{val}</span>
          </div>''')
    comp_rendered = "\n".join(comp_html)

    # Generate Layout items
    layout_html = []
    for label, val, sub, desc in s["layout"]:
        layout_html.append(f'''
          <div class="breakdown-item">
            <span class="breakdown-item-key">{label}</span>
            <span class="breakdown-item-val">{val}</span>
          </div>''')
    layout_rendered = "\n".join(layout_html)

    # Generate chips
    chips_html = " ".join([f'<span class="breakdown-chip">{c}</span>' for c in s["chips"]])

